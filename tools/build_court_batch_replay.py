"""Freeze one rules-only multi-source docket for the static page.

The page must show a real run, not a hand-written mock. This script runs the
same `core.court_batch.run_batch` the server uses and writes both the JSON and
the JS wrapper the static page loads.
"""
import datetime
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from core.court_batch import run_batch

OUT_JSON = os.path.join(ROOT, "data", "court_batch_replay.json")
OUT_JS = os.path.join(ROOT, "web", "court_batch_replay.js")

CLAIM = "Getting a flu vaccine gives you the flu."
SOURCES = [
    {"name": "CDC · injected vaccine",
     "text": "It is impossible to get influenza from the injected vaccine because the vaccine does not contain live virus."},
    {"name": "A leaflet that restates the claim",
     "text": "Getting a flu vaccine gives you the flu."},
    {"name": "Hand-hygiene source",
     "text": "Hand washing with soap reduces diarrhoeal disease in children."},
    {"name": "Vitamin D source",
     "text": "Vitamin D is important for bone health in adults."},
]


def main():
    payload = run_batch(CLAIM, SOURCES, live=False)
    if payload.get("error"):
        raise SystemExit(payload)
    payload["demo_label"] = "RECORDED MULTI-SOURCE RUN · RULES TRIAGE"
    payload["recorded_at"] = datetime.datetime.now(datetime.timezone.utc).isoformat()
    payload["replay_sources"] = SOURCES
    with open(OUT_JSON, "w", encoding="utf-8") as f:
        json.dump({"cases": {CLAIM: payload}}, f, ensure_ascii=False, indent=2)
    with open(OUT_JS, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/build_court_batch_replay.py. Real run, frozen. */\n")
        f.write("window.COURT_BATCH_REPLAY = ")
        json.dump({"cases": {CLAIM: payload}}, f, ensure_ascii=False)
        f.write(";\n")
    print("wrote", OUT_JSON)
    print("wrote", OUT_JS)
    print("verdicts", [r["verdict"] for r in payload["rows"]],
          "conflict", payload["summary"]["cross_source_conflict"])


if __name__ == "__main__":
    main()
